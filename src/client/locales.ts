/**
 * Flatten a nested dictionary into the locale service's dotted-key form.
 * @param {object} source - nested dictionary.
 * @param {string} prefix - accumulated key prefix.
 * @param {object} target - flat output.
 * @returns {object} flat dictionary.
 */
export function flattenDictionary(source: LocaleTree, prefix = '', target: LocaleDictionary = {}): LocaleDictionary {
  for (const [key, value] of Object.entries(source)) {
    const fullKey = prefix === '' ? key : `${prefix}.${key}`;
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) flattenDictionary(value, fullKey, target);
    else if (typeof value === 'string') target[fullKey] = value;
  }
  return target;
}

/** Apply `{name}` placeholders without depending on the active locale. */
export function interpolateMessage(text: string, params?: LocaleParams): string {
  if (params === undefined) return text;
  let value = text;
  for (const [name, replacement] of Object.entries(params)) value = value.split(`{${name}}`).join(String(replacement));
  return value;
}

/**
 * Build plural-aware placeholders for Replace in Files messages.
 *
 * English needs explicit occurrence/file units; Chinese keeps its own
 * measure-word wording and ignores these extra placeholders.
 * @param {(key: string) => string} t - active locale translator.
 * @param {number} matches - replaced occurrence count.
 * @param {number} files - changed file count.
 * @returns {{matches: number, files: number, matchUnit: string, fileUnit: string}} message params.
 */
export function searchReplaceCountParams(
  t: TranslateFunction,
  matches: unknown,
  files: unknown,
): { matches: number; files: number; matchUnit: string; fileUnit: string } {
  const matchCount = Math.max(0, Math.trunc(Number(matches) || 0));
  const fileCount = Math.max(0, Math.trunc(Number(files) || 0));
  return {
    matches: matchCount,
    files: fileCount,
    matchUnit: t(matchCount === 1 ? 'editor.searchReplaceMatchOne' : 'editor.searchReplaceMatchMany'),
    fileUnit: t(fileCount === 1 ? 'editor.searchReplaceFileOne' : 'editor.searchReplaceFileMany'),
  };
}

const englishMessages: LocaleDictionary = flattenDictionary(en);

/**
 * IDEA's Commit tool window stays in English even when the host locale is
 * Chinese: users compare it directly against IDEA and its action labels are
 * product terms (`Commit`, `Rollback`, `Shelve Silently`). Keep the
 * translation scoped to this tool window instead of changing shared labels.
 */
export const commitEnglish: TranslateFunction = (key, params) => {
  const text = englishMessages[key] ?? key;
  return interpolateMessage(text, params);
};

